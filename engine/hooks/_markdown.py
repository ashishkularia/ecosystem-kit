#!/usr/bin/env python3
"""Minimal Markdown <-> HTML conversion for artifact_sync (stdlib only).

The kit is stdlib-only (no `markdown`, no `html2text`), so both directions are
hand-rolled and DELIBERATELY LIMITED. Neither is a general-purpose converter
and neither is round-trip safe:

  md_to_html()  renders a documented CommonMark subset. Anything outside the
                subset is emitted as escaped text rather than guessed at.
  html_to_md()  extracts a READABLE DIGEST (headings, paragraphs, list items,
                links, code) via html.parser. It is lossy by construction —
                layout, styling and scripted content cannot survive.

Both are used only to generate the COUNTERPART of an artifact's source file.
The source is always stored verbatim and is the file a human edits; generated
files carry a banner saying so. See docs/ARCHITECTURE.md.

`_`-prefixed so the daemon's `engine/hooks/*.py` glob does not mistake this
helper for a hook module.
"""
import html
import re
from html.parser import HTMLParser

GENERATED_HTML_BANNER = (
    "<!-- GENERATED by ecosystem-kit artifact_sync from {source} — do not edit. "
    "Edit the source and republish. -->"
)
GENERATED_MD_BANNER = (
    "<!-- GENERATED by ecosystem-kit artifact_sync from {source} — do not edit. "
    "This is a lossy text digest, not the artifact. Edit the source and republish. -->"
)


# ───────────────────────── Markdown -> HTML ─────────────────────────

_INLINE_CODE = re.compile(r"`([^`]+)`")
_BOLD = re.compile(r"\*\*([^*]+)\*\*")
_ITALIC = re.compile(r"(?<![*\w])\*([^*\n]+)\*(?!\*)")
_LINK = re.compile(r"\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
_IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
_HR = re.compile(r"^\s{0,3}(?:-{3,}|\*{3,}|_{3,})\s*$")
_ATX = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_UL = re.compile(r"^\s{0,3}[-*+]\s+(.*)$")
_OL = re.compile(r"^\s{0,3}(\d+)[.)]\s+(.*)$")
_QUOTE = re.compile(r"^\s{0,3}>\s?(.*)$")
_FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})\s*([A-Za-z0-9_+-]*)\s*$")
_TABLE_DELIM = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")


def _safe_url(url: str) -> str:
    """Allow only benign URL schemes; `javascript:` and `data:` are dropped."""
    lowered = url.strip().lower()
    if lowered.startswith(("javascript:", "data:", "vbscript:")):
        return "#"
    return html.escape(url.strip(), quote=True)


def _inline(text: str) -> str:
    """Escape, then re-introduce the inline constructs we support."""
    placeholders = []

    def stash(rendered: str) -> str:
        placeholders.append(rendered)
        return "\x00%d\x00" % (len(placeholders) - 1)

    def do_image(m):
        return stash('<img src="%s" alt="%s">' % (_safe_url(m.group(2)), html.escape(m.group(1))))

    def do_link(m):
        return stash('<a href="%s">%s</a>' % (_safe_url(m.group(2)), _inline_no_links(m.group(1))))

    def do_code(m):
        return stash("<code>%s</code>" % html.escape(m.group(1)))

    text = _IMAGE.sub(do_image, text)
    text = _LINK.sub(do_link, text)
    text = _INLINE_CODE.sub(do_code, text)
    text = html.escape(text)
    text = _BOLD.sub(lambda m: "<strong>%s</strong>" % m.group(1), text)
    text = _ITALIC.sub(lambda m: "<em>%s</em>" % m.group(1), text)

    return re.sub(r"\x00(\d+)\x00", lambda m: placeholders[int(m.group(1))], text)


def _inline_no_links(text: str) -> str:
    """Inline rendering for link labels — no nested links."""
    text = _INLINE_CODE.sub(lambda m: "\x01%s\x01" % html.escape(m.group(1)), text)
    text = html.escape(text)
    text = _BOLD.sub(lambda m: "<strong>%s</strong>" % m.group(1), text)
    text = _ITALIC.sub(lambda m: "<em>%s</em>" % m.group(1), text)
    return text.replace("\x01", "").strip() or "link"


def _split_row(line: str) -> list:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def md_to_html(md_text: str) -> str:
    """Render a documented Markdown subset to an HTML fragment.

    Supported: ATX headings, fenced code, paragraphs, unordered/ordered lists,
    blockquotes, horizontal rules, GFM pipe tables, and the inline set
    (code, bold, italic, links, images). Everything else is escaped text.
    """
    lines = md_text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    out = []
    i = 0
    n = len(lines)

    while i < n:
        line = lines[i]

        fence = _FENCE.match(line)
        if fence:
            marker = fence.group(1)[0]
            lang = fence.group(2)
            body = []
            i += 1
            while i < n:
                close = _FENCE.match(lines[i])
                if close and close.group(1)[0] == marker:
                    i += 1
                    break
                body.append(lines[i])
                i += 1
            cls = ' class="language-%s"' % html.escape(lang) if lang else ""
            out.append("<pre><code%s>%s</code></pre>" % (cls, html.escape("\n".join(body))))
            continue

        if not line.strip():
            i += 1
            continue

        if _HR.match(line):
            out.append("<hr>")
            i += 1
            continue

        atx = _ATX.match(line)
        if atx:
            level = len(atx.group(1))
            out.append("<h%d>%s</h%d>" % (level, _inline(atx.group(2)), level))
            i += 1
            continue

        # GFM table: a header row followed by a delimiter row.
        if "|" in line and i + 1 < n and _TABLE_DELIM.match(lines[i + 1]):
            headers = _split_row(line)
            i += 2
            rows = []
            while i < n and lines[i].strip() and "|" in lines[i]:
                rows.append(_split_row(lines[i]))
                i += 1
            thead = "".join("<th>%s</th>" % _inline(h) for h in headers)
            tbody = "".join(
                "<tr>%s</tr>" % "".join("<td>%s</td>" % _inline(c) for c in r)
                for r in rows
            )
            out.append(
                '<div class="table-scroll"><table><thead><tr>%s</tr></thead>'
                "<tbody>%s</tbody></table></div>" % (thead, tbody)
            )
            continue

        if _QUOTE.match(line):
            body = []
            while i < n and _QUOTE.match(lines[i]):
                body.append(_QUOTE.match(lines[i]).group(1))
                i += 1
            out.append("<blockquote>%s</blockquote>" % md_to_html("\n".join(body)))
            continue

        if _UL.match(line) or _OL.match(line):
            ordered = bool(_OL.match(line))
            items = []
            while i < n:
                m = _OL.match(lines[i]) if ordered else _UL.match(lines[i])
                if not m:
                    break
                items.append(m.group(2) if ordered else m.group(1))
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(
                "<%s>%s</%s>" % (tag, "".join("<li>%s</li>" % _inline(it) for it in items), tag)
            )
            continue

        para = []
        while i < n and lines[i].strip() and not (
            _ATX.match(lines[i]) or _HR.match(lines[i]) or _FENCE.match(lines[i])
            or _UL.match(lines[i]) or _OL.match(lines[i]) or _QUOTE.match(lines[i])
        ):
            para.append(lines[i].strip())
            i += 1
        if para:
            out.append("<p>%s</p>" % _inline(" ".join(para)))

    return "\n".join(out)


