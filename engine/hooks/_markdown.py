def md_file_to_html_page(md_text: str, title: str, source_name: str, meta_html: str) -> str:
    """Wrap md_to_html output in a standalone, theme-aware HTML page."""
    return _HTML_SHELL.format(
        title=html.escape(title or source_name),
        banner=GENERATED_HTML_BANNER.format(source=html.escape(source_name)),
        meta=meta_html,
        body=md_to_html(md_text),
    )


# ───────────────────────── HTML -> Markdown digest ─────────────────────────

# NOTE: `head` is deliberately NOT here. Skipping it swallowed <title> before
# handle_starttag could reach the title branch, so every digest came back
# titleless. The tags that actually carry noise inside <head> (script, style)
# are skipped on their own account; <meta>/<link> are void and emit no data.
_SKIP_TAGS = {"script", "style", "noscript", "template", "svg"}
_BLOCK_TAGS = {
    "p", "div", "section", "article", "header", "footer", "main", "aside",
    "tr", "br", "blockquote", "pre", "figcaption", "dd", "dt",
}


class _DigestParser(HTMLParser):
    """Collect a readable text digest from an HTML document.

    Headings become Markdown headings, list items become bullets, links are
    kept inline as [text](href), and everything inside _SKIP_TAGS is dropped.
    """

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self._skip_depth = 0
        self._heading = None
        self._buf = []
        self._list_depth = 0
        self._in_li = False
        self._href = None
        self.title = None
        self._in_title = False

    # -- helpers
    def _flush(self):
        text = re.sub(r"[ \t]+", " ", "".join(self._buf)).strip()
        self._buf = []
        if not text:
            return
        if self._heading:
            self.parts.append("%s %s" % ("#" * self._heading, text))
        elif self._in_li:
            self.parts.append("- %s" % text)
        else:
            self.parts.append(text)

    def handle_starttag(self, tag, attrs):
        if self._skip_depth:
            if tag in _SKIP_TAGS:
                self._skip_depth += 1
            return
        if tag in _SKIP_TAGS:
            self._skip_depth = 1
            return
        if tag == "title":
            self._in_title = True
            return
        if tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self._flush()
            self._heading = int(tag[1])
            return
        if tag == "li":
            self._flush()
            self._in_li = True
            return
        if tag in ("ul", "ol"):
            self._flush()
            self._list_depth += 1
            return
        if tag == "a":
            self._href = dict(attrs).get("href")
            return
        if tag == "hr":
            self._flush()
            self.parts.append("---")
            return
        if tag in _BLOCK_TAGS:
            self._flush()

    def handle_endtag(self, tag):
        if self._skip_depth:
            if tag in _SKIP_TAGS:
                self._skip_depth -= 1
            return
        if tag == "title":
            self._in_title = False
            self.title = re.sub(r"\s+", " ", "".join(self._buf)).strip() or None
            self._buf = []
            return
        if tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self._flush()
            self._heading = None
            return
        if tag == "li":
            self._flush()
            self._in_li = False
            return
        if tag in ("ul", "ol"):
            self._flush()
            self._list_depth = max(0, self._list_depth - 1)
            return
        if tag == "a":
            self._href = None
            return
        if tag in _BLOCK_TAGS:
            self._flush()

    def handle_data(self, data):
        if self._skip_depth:
            return
        if self._in_title:
            self._buf.append(data)
            return
        if not data.strip():
            self._buf.append(" ")
            return
        if self._href and not self._href.startswith("#"):
            self._buf.append("[%s](%s)" % (data.strip(), self._href))
        else:
            self._buf.append(data)

    def close(self):
        super().close()
        self._flush()


def html_to_md(html_text: str) -> tuple:
    """Return (title, markdown_digest). Lossy by construction — see module doc."""
    parser = _DigestParser()
    try:
        parser.feed(html_text)
        parser.close()
    except Exception:
        # html.parser can raise on pathological input; a partial digest still
        # beats losing the record entirely.
        pass

    blocks = []
    for part in parser.parts:
        if blocks and blocks[-1] == part:
            continue
        blocks.append(part)

    return parser.title, "\n\n".join(blocks).strip()
